-- Phase 7 Step 1: Product add-on groups — schema and validation
-- ══════════════════════════════════════════════════════════════════════════════
--
-- WHAT THIS MIGRATION DOES
-- ------------------------
-- 1. Adds check_addon_groups() — IMMUTABLE validator used in the CHECK constraint.
-- 2. Adds addon_groups JSONB DEFAULT NULL column to products.
-- 3. Attaches the CHECK constraint.
--
-- BACKWARD COMPATIBILITY
-- ----------------------
-- addon_groups defaults to NULL.  All existing rows pass the NULL check.
-- No existing frontend code is affected — the column is not yet read.
-- validate_order_pricing is NOT changed here; that is migration 20261016000003.
--
-- ADDON GROUPS JSON SHAPE (enforced by check_addon_groups)
-- --------------------------------------------------------
-- [
--   {
--     "id":       "grp-<timestamp>-<random>",   -- unique within product
--     "label_en": "Packaging",
--     "label_bs": "Pakovanje",
--     "location": "product_page" | "personalization_modal",
--     "required": true | false,                  -- optional, defaults to false
--     "options": [
--       {
--         "id":               "opt-<timestamp>-<random>",   -- unique within group
--         "label_en":         "Standard",
--         "label_bs":         "Standardno",
--         "price_adjustment": 0.00,              -- non-negative, <= 99999
--         "text_required":    true | false        -- optional, defaults to false
--       }
--     ]
--   }
-- ]
--
-- LIMITS
-- ------
-- 1–10 groups per product; 1–20 options per group.
-- price_adjustment: 0.00–99999.00 BAM.
-- IDs are generated by the admin editor as "<prefix>-<ms>-<random>"; uniqueness
-- is enforced within the product only (IDs from different products may coincide).
--
-- ROLLBACK
-- --------
-- ALTER TABLE products DROP COLUMN addon_groups;
-- DROP FUNCTION IF EXISTS check_addon_groups(jsonb);

-- ─── 1. Validation function ───────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.check_addon_groups(grps jsonb)
RETURNS boolean
LANGUAGE plpgsql IMMUTABLE
SET search_path = public
AS $$
DECLARE
  grp       jsonb;
  opt       jsonb;
  seen_grps text[]  := '{}';
  seen_opts text[]  := '{}';
  gid       text;
  oid       text;
  loc       text;
  padj      numeric;
BEGIN
  -- NULL means no add-on groups configured; always valid.
  IF grps IS NULL THEN
    RETURN true;
  END IF;

  IF jsonb_typeof(grps) != 'array' THEN
    RETURN false;
  END IF;

  IF jsonb_array_length(grps) < 1 OR jsonb_array_length(grps) > 10 THEN
    RETURN false;
  END IF;

  FOR grp IN SELECT * FROM jsonb_array_elements(grps) LOOP

    -- id: non-empty string, unique within this product's group list
    gid := trim(grp ->> 'id');
    IF gid IS NULL OR gid = '' THEN RETURN false; END IF;
    IF gid = ANY(seen_grps) THEN RETURN false; END IF;
    seen_grps := array_append(seen_grps, gid);

    -- label_en / label_bs: non-empty strings
    IF coalesce(trim(grp ->> 'label_en'), '') = '' THEN RETURN false; END IF;
    IF coalesce(trim(grp ->> 'label_bs'), '') = '' THEN RETURN false; END IF;

    -- location: exactly one of the two allowed values
    loc := grp ->> 'location';
    IF loc NOT IN ('product_page', 'personalization_modal') THEN RETURN false; END IF;

    -- required: optional boolean; if present must be boolean JSON type
    IF (grp -> 'required') IS NOT NULL
       AND jsonb_typeof(grp -> 'required') != 'boolean' THEN
      RETURN false;
    END IF;

    -- options: required, must be a non-empty array of 1–20 items
    IF (grp -> 'options') IS NULL
       OR jsonb_typeof(grp -> 'options') != 'array' THEN
      RETURN false;
    END IF;
    IF jsonb_array_length(grp -> 'options') < 1
       OR jsonb_array_length(grp -> 'options') > 20 THEN
      RETURN false;
    END IF;

    -- validate each option
    seen_opts := '{}';
    FOR opt IN SELECT * FROM jsonb_array_elements(grp -> 'options') LOOP

      -- id: non-empty string, unique within this group
      oid := trim(opt ->> 'id');
      IF oid IS NULL OR oid = '' THEN RETURN false; END IF;
      IF oid = ANY(seen_opts) THEN RETURN false; END IF;
      seen_opts := array_append(seen_opts, oid);

      -- label_en / label_bs: non-empty strings
      IF coalesce(trim(opt ->> 'label_en'), '') = '' THEN RETURN false; END IF;
      IF coalesce(trim(opt ->> 'label_bs'), '') = '' THEN RETURN false; END IF;

      -- price_adjustment: parseable numeric, 0 ≤ x ≤ 99999
      BEGIN
        padj := (opt ->> 'price_adjustment')::numeric;
      EXCEPTION WHEN OTHERS THEN
        RETURN false;
      END;
      IF padj IS NULL OR padj < 0 OR padj > 99999 THEN RETURN false; END IF;

      -- text_required: optional boolean
      IF (opt -> 'text_required') IS NOT NULL
         AND jsonb_typeof(opt -> 'text_required') != 'boolean' THEN
        RETURN false;
      END IF;

    END LOOP;
  END LOOP;

  RETURN true;
END;
$$;

-- ─── 2. Column ────────────────────────────────────────────────────────────────

ALTER TABLE products
  ADD COLUMN IF NOT EXISTS addon_groups jsonb;

-- ─── 3. CHECK constraint ──────────────────────────────────────────────────────

ALTER TABLE products
  DROP CONSTRAINT IF EXISTS products_addon_groups_valid;

ALTER TABLE products
  ADD CONSTRAINT products_addon_groups_valid
  CHECK (check_addon_groups(addon_groups));
