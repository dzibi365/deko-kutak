-- Phase 7 Step 4: verify_order_pricing RPC + updated place_order
-- ══════════════════════════════════════════════════════════════════════════════
--
-- WHAT THIS MIGRATION DOES
-- ------------------------
-- 1. Creates verify_order_pricing(p_items) — read-only price check RPC.
-- 2. Replaces place_order with a backward-compatible version that accepts
--    an optional p_expected_total parameter for TOCTOU protection.
--
-- OVERLOAD SAFETY
-- ---------------
-- PostgreSQL treats functions with different parameter lists as distinct
-- overloads.  CREATE OR REPLACE on the existing 11-parameter place_order would
-- create a NEW 12-parameter overload while leaving the old 11-parameter one in
-- place.  Two overloads with the same name make GRANT/REVOKE-by-name ambiguous.
--
-- Solution: DROP the existing 11-parameter function first, then CREATE the new
-- 12-parameter version.  This leaves exactly one overload.  DROP IF EXISTS
-- avoids failure on a fresh schema.  The DEFAULT NULL on p_expected_total means
-- existing callers that omit the argument continue to work without changes.
--
-- VERIFY_ORDER_PRICING
-- --------------------
-- Purpose: allows Checkout to get the server-authoritative total BEFORE placing
-- an order, so any price changes since add-to-cart are visible to the customer.
-- Security:
--   • SECURITY DEFINER — runs as owner (postgres) to read products and
--     store_settings without RLS interference.
--   • SET search_path = public — prevents search_path manipulation.
--   • GRANT TO anon, authenticated — callable by storefront guests and users.
--   • Thin wrapper: delegates entirely to internal_calculate_order_totals.
--   • No writes, no sequences, no rate-limit impact.
-- Returns: (subtotal, shipping_cost, total) as NUMERIC(10,2).
-- The frontend compares response.total against centsToKm(shipping.totalCents)
-- (the full displayed total, NOT CartContext.total which is the product subtotal
-- only).  A difference > 0.01 KM triggers the price-change acknowledgment flow.
--
-- PLACE_ORDER CHANGES
-- -------------------
-- The new p_expected_total parameter enables the atomic TOCTOU guard:
--   1. If provided, place_order calls set_config('app.expected_total', x, true).
--      is_local=true makes the value transaction-local — gone after commit/rollback.
--   2. The validate_order_pricing trigger reads the value via current_setting and
--      rejects the order if |calculated - expected| >= 0.01 KM (any 1-cent change).
--   3. If omitted (DEFAULT NULL), set_config is not called, the guard is skipped,
--      and legacy callers see identical behaviour.
-- Everything else in place_order is byte-for-byte identical to the baseline.
--
-- EXISTING BUSINESS LOGIC PRESERVED
-- ----------------------------------
-- • order_number from DB sequence — generated by trigger, not RPC.
-- • status hardcoded to 'pending' — client cannot influence it.
-- • email_token generated server-side (gen_random_uuid()).
-- • enforce_order_rate_limit (trg_orders_rate_limit) still fires before the
--   pricing trigger (alphabetical order: "trg_orders_" < "trg_validate_").
-- • protect_order_financials trigger is unaffected.
-- • All financial columns are still overwritten by the trigger.
--
-- ROLLBACK
-- --------
-- DROP FUNCTION IF EXISTS public.verify_order_pricing(jsonb);
-- DROP FUNCTION IF EXISTS public.place_order(text,text,text,text,text,text,text,jsonb,numeric,text,text,numeric);
-- Restore original place_order from 20261014000001 body (preserved in git).

-- ─── 1. verify_order_pricing ─────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.verify_order_pricing(p_items JSONB)
RETURNS TABLE(subtotal NUMERIC(10,2), shipping_cost NUMERIC(10,2), total NUMERIC(10,2))
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT subtotal, shipping_cost, total
  FROM   public.internal_calculate_order_totals(p_items);
$$;

REVOKE EXECUTE ON FUNCTION public.verify_order_pricing(jsonb) FROM PUBLIC;
GRANT  EXECUTE ON FUNCTION public.verify_order_pricing(jsonb) TO anon;
GRANT  EXECUTE ON FUNCTION public.verify_order_pricing(jsonb) TO authenticated;

-- ─── 2. place_order ──────────────────────────────────────────────────────────

-- Drop the existing 11-parameter overload to avoid ambiguous overloads after
-- adding p_expected_total.  DROP IF EXISTS is safe on a fresh schema.
DROP FUNCTION IF EXISTS public.place_order(
  text, text, text, text, text, text, text, jsonb, numeric, text, text
);

CREATE FUNCTION public.place_order(
  p_customer_name    text,
  p_customer_email   text,
  p_customer_phone   text,
  p_customer_address text,
  p_customer_city    text,
  p_customer_postal  text,
  p_payment_method   text,
  p_items            jsonb,
  p_subtotal         numeric,
  p_note             text,
  p_lang             text,
  p_expected_total   numeric DEFAULT NULL   -- optional; when provided enables TOCTOU guard
) RETURNS TABLE(order_number text, email_token uuid)
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public
AS $$
DECLARE
  v_email_token  uuid := gen_random_uuid();
  v_order_number text;
BEGIN
  -- When the caller provides a verified total (from verify_order_pricing), store
  -- it as a transaction-local GUC so the pricing trigger can compare it to its
  -- own calculation.  is_local=true guarantees the value is gone after this
  -- transaction ends — no cross-request leakage.
  IF p_expected_total IS NOT NULL THEN
    PERFORM set_config('app.expected_total', p_expected_total::text, true);
  END IF;

  INSERT INTO orders (
    customer_name, customer_email, customer_phone,
    customer_address, customer_city, customer_postal,
    payment_method, items, subtotal, note, status, lang,
    email_token
  ) VALUES (
    p_customer_name, p_customer_email, p_customer_phone,
    p_customer_address, p_customer_city, p_customer_postal,
    p_payment_method, p_items, p_subtotal, p_note, 'pending', p_lang,
    v_email_token
  )
  RETURNING orders.order_number INTO v_order_number;

  RETURN QUERY SELECT v_order_number, v_email_token;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.place_order(
  text, text, text, text, text, text, text, jsonb, numeric, text, text, numeric
) FROM PUBLIC;

GRANT  EXECUTE ON FUNCTION public.place_order(
  text, text, text, text, text, text, text, jsonb, numeric, text, text, numeric
) TO anon;

GRANT  EXECUTE ON FUNCTION public.place_order(
  text, text, text, text, text, text, text, jsonb, numeric, text, text, numeric
) TO authenticated;
